let txSeq = 0;
function t(
  date: string,
  customerId: string,
  productId: string,
  qty: number,
  unitPrice: number
): SalesTransaction {
  txSeq += 1;
  return { id: `s${String(txSeq).padStart(3, "0")}`, date, customerId, productId, qty, unitPrice };
}

